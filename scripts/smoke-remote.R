if (dir.exists(".library")) .libPaths(c(normalizePath(".library"), .libPaths()))
url <- Sys.getenv("MCP_ENDPOINT")
if (!grepl("^https://[^/]+/.*/?mcp$|^https://[^/]+/mcp$", url)) stop("Set MCP_ENDPOINT to the verified HTTPS /mcp URL")
entry <- list(url = url)
if (nzchar(Sys.getenv("CLOUD_RUN_ID_TOKEN"))) entry$headers <- list(Authorization = "Bearer ${CLOUD_RUN_ID_TOKEN}")
path <- tempfile(fileext = ".json")
jsonlite::write_json(list(mcpServers = list(loadings = entry)), path, auto_unbox = TRUE)
tryCatch({
  tools <- mcptools::mcp_tools(path)
  stopifnot(length(tools) == 3L)
  source("R/utils.R"); source("R/analysis.R")
  result <- tools[[which(vapply(tools, function(t) grepl("analyze_pca$", t@name), logical(1)))]](x = demo_data()$x, components = 2L, max_rows = 10L)
  stopifnot(result@value$ok)
  print(result)
}, finally = unlink(path))
