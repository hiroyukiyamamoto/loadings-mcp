source("R/utils.R"); source("R/analysis.R")
demo <- demo_data()
result <- analyze_pca(demo$x, components = 2L, max_rows = 150L)
stopifnot(result$ok)
dir.create("docs/data", recursive = TRUE, showWarnings = FALSE)
dir.create("docs/images", recursive = TRUE, showWarnings = FALSE)
jsonlite::write_json(result, "docs/data/iris-pca.json", auto_unbox = TRUE, pretty = TRUE, na = "null", digits = 10)
jsonlite::write_json(list(tool = "analyze_pca", arguments = list(x = demo$x, components = 2L, max_rows = 150L)), "examples/iris-pca-input.json", auto_unbox = TRUE, pretty = TRUE)
svg("docs/images/iris-scores.svg", width = 7, height = 4.5)
scores <- do.call(rbind, lapply(result$scores$values, unlist))
plot(scores, col = c("#188078", "#cb6838", "#5961a5")[iris$Species], pch = 19, xlab = "PC1", ylab = "PC2", main = "Iris PCA scores (autoscaled)")
legend("topright", levels(iris$Species), col = c("#188078", "#cb6838", "#5961a5"), pch = 19, bty = "n")
dev.off()
svg("docs/images/iris-loadings.svg", width = 7, height = 4.5)
loadings <- do.call(rbind, lapply(result$loadings$values, unlist))
plot(loadings, xlim = c(-1.15, 1.15), ylim = c(-1.15, 1.15), xlab = "PC1 correlation loading", ylab = "PC2 correlation loading", pch = 19, col = "#188078", main = "Iris PCA correlation loadings")
abline(h = 0, v = 0, col = "grey80")
text(loadings, labels = names(iris)[1:4], pos = 3, cex = .8)
dev.off()
