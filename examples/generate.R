if (dir.exists(".library")) .libPaths(c(normalizePath(".library"), .libPaths()))
source("R/utils.R"); source("R/analysis.R")
demo <- demo_data()
result <- analyze_pca(demo$x, components = 2L, max_rows = 400L)
stopifnot(result$ok)
dir.create("docs/data", recursive = TRUE, showWarnings = FALSE)
dir.create("docs/images", recursive = TRUE, showWarnings = FALSE)
jsonlite::write_json(result, "docs/data/fasting-pca.json", auto_unbox = TRUE, pretty = TRUE, na = "null", digits = 10)
jsonlite::write_json(list(tool = "analyze_pca", arguments = list(x = demo$x, components = 2L, max_rows = 400L)), "examples/fasting-pca-input.json", auto_unbox = TRUE, pretty = TRUE, digits = NA)
groups <- max.col(numeric_matrix(demo$y,"y"))
colors <- c("#2464a3", "#d17a39", "#65915b")
svg("docs/images/fasting-scores.svg", width = 7, height = 4.5)
scores <- do.call(rbind, lapply(result$scores$values, unlist))
plot(scores, col = colors[groups], pch = 19, xlab = "PC1", ylab = "PC2", main = "Fasting metabolome PCA (10 samples, 282 metabolites)")
legend("topright", unlist(demo$group_columns), col = colors[1:2], pch = 19, bty = "n")
dev.off()
svg("docs/images/fasting-loadings.svg", width = 7, height = 4.5)
loadings <- do.call(rbind, lapply(result$loadings$values, unlist))
plot(loadings, xlim = c(-1.3, 1.3), ylim = c(-1.25, 1.25), xlab = "PC1 correlation loading", ylab = "PC2 correlation loading", pch = 19, cex=.55, col = "#2464a3", main = "Fasting metabolome: all 282 correlation loadings")
abline(h = 0, v = 0, col = "grey80")
top <- head(order(rowSums(loadings^2), decreasing=TRUE), 6)
text(loadings[top,,drop=FALSE], labels = substr(unlist(demo$variables)[top],1,24), pos = 3, cex = .6)
dev.off()

